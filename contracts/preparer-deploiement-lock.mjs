/* preparer-deploiement-lock.mjs — FREEZES the deployment data of TBlockLock (Phil 2026-11-10: "the holder stage = TBLOCK locked, 1 week minimum").
 * ⛔ THIS SCRIPT SIGNS NOTHING AND SENDS NOTHING. It writes ../lock-deploiement.js; deployer-lock.html offers it to the connected wallet (one signature).
 * The only constructor argument is the TBLOCK address. No owner, no fee: whoever signs the deploy gets NO right over the contract.
 * Usage (from contracts/): forge build && node preparer-deploiement-lock.mjs   (after the deploy was READ on chain: ADRESSE_LOCK=0x… node …) */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
const ICI = path.dirname(fileURLToPath(import.meta.url));
const TBLOCK = '0xb200000000000000000000ba9bf8330307f8830e';
const A = JSON.parse(fs.readFileSync(path.join(ICI, 'out', 'TBlockLock.sol', 'TBlockLock.json'), 'utf8'));
const c = (A.abi.find((x) => x.type === 'constructor') || {}).inputs || [];
if (c.map((x) => x.type).join() !== 'address') throw new Error('TBlockLock constructor shape differs');
for (const f of ['lock', 'extend', 'requestWithdraw', 'cancelWithdraw', 'withdraw', 'lockedOf', 'activeLockedOf', 'unlockAtOf', 'requestedAtOf', 'withdrawableAtOf', 'totalLocked', 'MIN_LOCK', 'MAX_LOCK', 'WITHDRAW_DELAY', 'TBLOCK'])
  if (!A.abi.some((x) => x.type === 'function' && x.name === f)) throw new Error('TBlockLock lacks ' + f);
if (A.abi.some((x) => x.type === 'function' && /owner|admin|rescue|pause|upgrade|sweep/i.test(x.name))) throw new Error('TBlockLock grew an admin function');
const creation = String(A.bytecode.object) + TBLOCK.slice(2).padStart(64, '0');
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const meta = typeof A.metadata === 'string' ? JSON.parse(A.metadata) : (A.metadata || {});
const v = process.env.ADRESSE_LOCK;
if (v && !/^0x[0-9a-fA-F]{40}$/.test(v)) throw new Error('ADRESSE_LOCK is not an address');
fs.writeFileSync(path.join(ICI, '..', 'lock-deploiement.js'), `/* lock-deploiement.js — GENERATED by contracts/preparer-deploiement-lock.mjs. DO NOT EDIT BY HAND.
 * The UNSIGNED deployment data of TBlockLock. Nothing here signs or sends. */
export const LOCK_DEPLOIEMENT = Object.freeze({
  chaine: 8453,
  compilateur: ${JSON.stringify((meta.compiler || {}).version || null)},
  tblock: '${TBLOCK}',
  minLockSecondes: 604800,
  retraitSecondes: 604800, /* WITHDRAW_DELAY: an exit is requested, then paid 7 days later at the earliest (Phil 2026-11-10) */
  sha256Source: '${sha(fs.readFileSync(path.join(ICI, 'src/TBlockLock.sol')))}',
  sha256Creation: '${sha(creation)}', octets: ${(creation.length - 2) / 2}, creation: '${creation}',
  /* filled after the deployment was READ on chain */
  adresse: ${v ? "'" + v.toLowerCase() + "'" : 'null'},
});
`);
console.log('lock-deploiement.js written · sha256 ' + sha(creation) + ' · ' + (creation.length - 2) / 2 + ' bytes');
